//! Deployment profile — M4 T34 (plan v2; review finding #16).
//!
//! Role-separated deployment: serve (web), watch (worker), cast
//! (experiment) are THREE processes with DIFFERENT credential needs.
//! The cast worker must structurally NOT inherit identity-admin
//! secrets, approval credentials, or production connector tokens —
//! the T23 sandbox env whitelist is the enforcement point inside the
//! process; this module is the OS-level boundary description and its
//! checker.
//!
//! Single OS user is a DOCUMENTED limitation: the separation here is
//! about which files each role READS, verified by checker + tests,
//! not kernel-level sandboxing (that is M5 containerization).

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum Role {
    /// web UI + approval API: identity.db, scope.db, ledger (RO+RW)
    Serve,
    /// worker: ledger RW, workdir, gh_token (PR publish), notifier
    Watch,
    /// casting experiments: corpus, casting dir, LLM api keys ONLY.
    /// Must NOT see: identity.db, gh_token, notifier.env
    Cast,
}

#[derive(Debug, Clone)]
pub struct FileSpec {
    pub path: PathBuf,
    pub mode: u32,
    pub owner_read_only_for: Vec<Role>,
}

/// The credential boundary table: which role may read which file.
/// (role, file) pairs not listed = denied by default.
pub fn boundary() -> BTreeMap<Role, Vec<PathBuf>> {
    let home = std::env::var("HOME").unwrap_or_else(|_| "/home/cosmo".into());
    let h = PathBuf::from(&home);
    let mut m = BTreeMap::new();
    m.insert(
        Role::Serve,
        vec![
            h.join(".foundry/ledger.db"),
            h.join(".foundry/ledger.identity.db"),
            h.join(".foundry/ledger.scope.db"),
        ],
    );
    m.insert(
        Role::Watch,
        vec![
            h.join(".foundry/ledger.db"),
            h.join(".foundry/gh_token"),
            h.join(".foundry/die.env"),
            h.join(".foundry/notifier.env"),
        ],
    );
    m.insert(
        Role::Cast,
        vec![
            h.join(".foundry/corpus"),
            h.join(".foundry/casting"),
            h.join(".foundry/ledger.db"), // read for baseline corpus only
        ],
    );
    m
}

#[derive(Debug, PartialEq)]
pub enum CheckOutcome {
    Ok,
    Violations(Vec<String>),
}

/// Verify the deployment profile on this host:
/// 1. every credential file listed for a role exists with mode 600
/// 2. files FORBIDDEN for a role do not appear in its boundary set
///    (structural check of the table itself)
/// 3. actual on-disk permission bits match the spec
pub fn check_profile() -> CheckOutcome {
    let mut v = vec![];
    let b = boundary();

    // structural: forbidden sets
    let forbidden_cast = [
        "identity.db",
        "gh_token",
        "notifier.env",
        "die.env",
    ];
    for (role, files) in &b {
        for f in files {
            let name = f.file_name().map(|x| x.to_string_lossy().to_string()).unwrap_or_default();
            if *role == Role::Cast && forbidden_cast.iter().any(|x| name.contains(x)) {
                v.push(format!("BOUNDARY VIOLATION: cast may not access {name}"));
            }
        }
    }

    // on-disk: watch credential files must be 600 when present
    let home = std::env::var("HOME").unwrap_or_else(|_| "/home/cosmo".into());
    for cred in ["gh_token", "die.env", "notifier.env"] {
        let p = Path::new(&home).join(".foundry").join(cred);
        if p.exists() {
            if let Ok(meta) = std::fs::metadata(&p) {
                use std::os::unix::fs::PermissionsExt;
                let mode = meta.permissions().mode() & 0o777;
                if mode != 0o600 {
                    v.push(format!("PERMISSION: {} has mode {:o}, expected 600", p.display(), mode));
                }
            }
        }
    }

    if v.is_empty() {
        CheckOutcome::Ok
    } else {
        CheckOutcome::Violations(v)
    }
}

/// Generate the systemd units for the three roles. Caller writes them
/// to /etc/systemd/system (documented in deploy README).
pub fn systemd_units() -> String {
    let home = std::env::var("HOME").unwrap_or_else(|_| "/home/cosmo".into());
    let bin = format!("{home}/.cargo/bin/foundry");
    format!(
        r##"# generated by `foundry deploy-profile` (M4 T34) — write to
# /etc/systemd/system/, then: systemctl daemon-reload && systemctl enable --now foundry-serve

# ---- foundry-serve: web UI + approval API (localhost by default) ----
[Unit]
Description=Foundry serve (web + approval API)
After=network.target

[Service]
Type=simple
User=cosmo
ExecStart={bin} serve --db {home}/.foundry/ledger.db --bind 127.0.0.1:8080
Restart=on-failure
# hardening
NoNewPrivileges=yes
ProtectSystem=strict
ProtectHome=read-only
ReadWritePaths={home}/.foundry
PrivateTmp=yes

[Install]
WantedBy=default.target

# ---- foundry-watch: worker (ledger RW, publishers) ----
[Unit]
Description=Foundry watch (worker loop)
After=network.target foundry-serve.service

[Service]
Type=simple
User=cosmo
ExecStart={bin} watch --every 300
Restart=on-failure
NoNewPrivileges=yes
ProtectSystem=strict
ReadWritePaths={home}/.foundry {home}/.foundry-work
PrivateTmp=yes

[Install]
WantedBy=default.target

# ---- foundry-cast: casting experiments (NON-PROMOTING observation) ----
[Unit]
Description=Foundry casting (experiment loop)
After=network.target

[Service]
Type=simple
User=cosmo
# NOTE (review #16): single-OS-user limitation — the structural
# boundary is the boundary() table + sandbox env whitelist (T23),
# NOT kernel isolation. Containerization lands in M5.
ExecStart={bin} casting --run-profile
Restart=no
NoNewPrivileges=yes
ProtectSystem=strict
ReadWritePaths={home}/.foundry/casting {home}/.foundry/corpus
PrivateTmp=yes

[Install]
WantedBy=default.target
"##
    )
}

/// Human-readable summary of the three-role topology + the honest
/// limitations (single OS user, loopback-only TLS boundary).
pub fn readme() -> String {
    format!(
        r#"# Foundry deployment profile (M4 T34)

## Topology — one binary, three roles

| role | process | reads/writes | must NEVER see |
|---|---|---|---|
| serve | `foundry serve` | ledger, identity.db, scope.db | gh_token, LLM keys |
| watch | `foundry watch` | ledger RW, gh_token, die.env, notifier.env | identity.db |
| cast | `foundry casting` | corpus, casting/, ledger (RO baseline) | identity.db, gh_token, notifier.env, die.env |

## Credentials

All credential files are chmod 600 under ~/.foundry/ (checker
verifies). LLM API keys live in the operator's shell env file,
loaded ONLY by the cast process (T23 sandbox whitelists env per
candidate profile).

## Honest limitations (documented, not hidden)

1. **Single OS user**: all three roles run as one user. The
   boundary is the table + checker + sandbox env whitelist, not
   kernel isolation. Container-level separation is M5.
2. **TLS/loopback**: serve binds 127.0.0.1 by default. Remote
   access requires a reverse proxy with TLS terminated OUTSIDE this
   deployment; the trust boundary at the proxy must be documented
   by the operator.
3. **Backups**: ledger.db + identity.db + scope.db must be backed
   up TOGETHER (reports pin ledger prefixes; identity pins actor
   semantics).

## Verify

    foundry deploy-profile --check
"#
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn cast_role_never_sees_credentials() {
        let b = boundary();
        let cast_files = b.get(&Role::Cast).unwrap();
        for f in cast_files {
            let name = f.file_name().unwrap().to_string_lossy();
            assert!(
                !name.contains("gh_token") && !name.contains("identity") && !name.contains("notifier") && !name.contains("die.env"),
                "cast boundary leak: {name}"
            );
        }
    }

    #[test]
    fn serve_role_never_sees_publisher_credentials() {
        let b = boundary();
        let serve_files = b.get(&Role::Serve).unwrap();
        for f in serve_files {
            let name = f.file_name().unwrap().to_string_lossy();
            assert!(!name.contains("gh_token"), "serve must not publish");
            assert!(!name.contains("notifier"), "serve must not notify");
        }
    }

    #[test]
    fn profile_check_runs_on_this_host() {
        // on the dev host the credential files exist at 600 — the
        // checker must pass here (this is the deployment host spec)
        match check_profile() {
            CheckOutcome::Ok => {}
            CheckOutcome::Violations(v) => panic!("profile violations: {v:?}"),
        }
    }

    #[test]
    fn systemd_units_mention_all_three_roles() {
        let u = systemd_units();
        assert!(u.contains("foundry-serve"));
        assert!(u.contains("foundry-watch"));
        assert!(u.contains("foundry-cast"));
        // hardening present
        assert!(u.contains("NoNewPrivileges=yes"));
        assert!(u.contains("ProtectSystem=strict"));
        // honest limitation documented in the unit itself
        assert!(u.contains("single-OS-user limitation"));
    }

    #[test]
    fn readme_documents_limitations() {
        let r = readme();
        assert!(r.contains("Single OS user"));
        assert!(r.contains("TLS"));
        assert!(r.contains("backed") && r.contains("TOGETHER"), "backup coupling documented");
    }
}
